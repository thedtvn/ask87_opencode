import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
await build({ entryPoints: ['src/broker-main.ts'], outfile: 'dist/broker.cjs', bundle: true, platform: 'node', format: 'cjs', target: 'node22', sourcemap: false });
const files = [
  'dist/broker.cjs', 'src/keyboard-worker.cjs',
  'vendor/attack-shark-x87/package.json', 'vendor/attack-shark-x87/LICENSE', 'vendor/attack-shark-x87/SOURCE.json',
  'vendor/attack-shark-x87/lib/ask87_ts/dist/index.js', 'vendor/attack-shark-x87/lib/ask87_ts/dist/enums.js',
  ...['win32-x64', 'win32-arm64', 'linux-x64-gnu', 'linux-arm64-gnu', 'darwin-x64', 'darwin-arm64'].map(platform => `vendor/attack-shark-x87/lib/ask87_ts/native/${platform}/ask87.node`),
];
const contents = Object.fromEntries(await Promise.all(files.map(async file => [file, (await readFile(file)).toString('base64')])));
const data = gzipSync(JSON.stringify(contents), { level: 9 });
const digest = createHash('sha256').update(data).digest('hex');
await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/runtime-assets.ts', `// Generated by scripts/build-broker.mjs; do not edit.\nexport const runtimeDigest = ${JSON.stringify(digest)};\nexport const runtimeArchive = ${JSON.stringify(data.toString('base64'))};\n`);
